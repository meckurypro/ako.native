// scripts/sync-alpha-tokens.mjs
// Opacity-modified colour classes (bg-ink/10, text-white/80 …) compile to
// color-mix() and did not render reliably on device (menus/navs/pills came out
// see-through or wrong in dark mode). Instead of `bg-ink/10` the codebase uses
// pre-computed tokens: `bg-ink-a10`, `text-white-a80`, `border-danger-a30` …
// where `a<NN>` is the alpha in percent.
//
// This script finds every `-a<NN>` token used in src/ and regenerates:
//   • src/theme/alphaTokens.ts   – which theme colours need which alphas (runtime, per palette)
//   • the marked block in src/global.css – default values so Tailwind emits the utilities
//
// Usage:
//   node scripts/sync-alpha-tokens.mjs            regenerate from current usage
//   node scripts/sync-alpha-tokens.mjs --rewrite  first convert any remaining `x-y/NN` classes to `x-y-aNN`
//
// Run it after adding a new `-aNN` class. Never write `bg-ink/10` style classes.
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const SRC = join(ROOT, "src");
const PREFIX = "bg|text|border|ring|fill|stroke|shadow|from|to|via|divide|outline|decoration|placeholder|caret|accent";

// Theme colours that change at runtime with the palette (see palettes.ts)…
const RUNTIME = {
  canvas: "#F7F4EF", surface: "#FDFBF6", ink: "#1F1D1A", "ink-muted": "#6B675F", accent: "#3D5A45",
  "accent-hover": "#2F4636", "accent-soft": "#E3E9E1", border: "#E9E4D8", danger: "#A64B3F", pushback: "#B8862E",
  "stance-support": "#4E8A62", "stance-disagree": "#B4574A", "stance-pushback": "#B8862E",
  highlight: "#BFE6C6",
};
// …and fixed ones.
const STATIC = {
  white: "#FFFFFF", black: "#000000",
  "overlay-surface": "#1C1C1E", "overlay-surface-raised": "#2C2C2E", "overlay-ink": "#F5F5F7",
  "overlay-ink-muted": "#98989D", "overlay-danger": "#D6968A", "overlay-accent": "#8FB89C",
};

function walk(dir, out = []) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(tsx?|jsx?)$/.test(f) && !p.endsWith("alphaTokens.ts")) out.push(p);
  }
  return out;
}
const files = walk(SRC);
const names = [...Object.keys(RUNTIME), ...Object.keys(STATIC)].sort((a, b) => b.length - a.length).join("|");

if (process.argv.includes("--rewrite")) {
  const re = new RegExp(`(^|[^\\w/-])((?:[a-z]+:)*(?:${PREFIX})-(?:${names}))\\/(\\d{1,3})(?![\\w.])`, "g");
  let n = 0;
  for (const f of files) {
    const s = readFileSync(f, "utf8");
    const t = s.replace(re, (_, pre, cls, pct) => { n++; return `${pre}${cls}-a${pct}`; });
    if (t !== s) writeFileSync(f, t);
  }
  console.log(`rewrote ${n} class usages`);
}

// collect
const used = {}; // name -> Set(pct)
const useRe = new RegExp(`(?:${PREFIX})-(${names})-a(\\d{1,3})(?![\\w])`, "g");
for (const f of files) {
  const s = readFileSync(f, "utf8");
  for (const m of s.matchAll(useRe)) (used[m[1]] ??= new Set()).add(Number(m[2]));
}
const hexA = (hex, pct) => hex + Math.round((pct / 100) * 255).toString(16).padStart(2, "0").toUpperCase();
const sorted = (set) => [...set].sort((a, b) => a - b);

// 1) alphaTokens.ts (runtime names only)
const runtimeUsed = Object.fromEntries(Object.keys(RUNTIME).filter((k) => used[k]).map((k) => [k, sorted(used[k])]));
writeFileSync(
  join(SRC, "theme/alphaTokens.ts"),
  `// GENERATED by scripts/sync-alpha-tokens.mjs — do not edit by hand.
// Alpha variants of theme colours, used as \`bg-ink-a10\`-style classes (see the script for why).
export const ALPHA_TOKENS: Record<string, number[]> = ${JSON.stringify(runtimeUsed, null, 2)};

/** "#RRGGBB" + percent → "#RRGGBBAA". */
export function hexWithAlpha(hex: string, pct: number): string {
  return hex + Math.round((pct / 100) * 255).toString(16).padStart(2, "0").toUpperCase();
}
`
);

// 2) global.css block
const lines = [];
for (const [k, v] of Object.entries({ ...RUNTIME, ...STATIC })) {
  if (!used[k]) continue;
  for (const pct of sorted(used[k])) lines.push(`  --color-${k}-a${pct}: ${hexA(v, pct)};`);
}
const block = `/* alpha-tokens:start (generated by scripts/sync-alpha-tokens.mjs) */\n@theme {\n${lines.join("\n")}\n}\n/* alpha-tokens:end */`;
const cssPath = join(SRC, "global.css");
let css = readFileSync(cssPath, "utf8");
if (css.includes("/* alpha-tokens:start")) css = css.replace(/\/\* alpha-tokens:start[\s\S]*?alpha-tokens:end \*\//, block);
else css = css.trimEnd() + "\n\n" + block + "\n";
writeFileSync(cssPath, css);
console.log(`tokens: ${lines.length}`);
